/* ---------- контур черты: полоса толщиной W вокруг средней линии со скруглёнными концами ---------- */
const r1 = v => Math.round(v * 10) / 10;
function outline(pts, w = W) {
  const h = w / 2, n = pts.length;
  const normal = i => {
    const a = pts[Math.max(0, i - 1)], b = pts[Math.min(n - 1, i + 1)];
    const dx = b[0] - a[0], dy = b[1] - a[1], len = Math.hypot(dx, dy) || 1;
    return [-dy / len, dx / len];
  };
  const left = [], right = [];
  pts.forEach((p, i) => { const [nx, ny] = normal(i); left.push([p[0] + nx * h, p[1] + ny * h]); right.push([p[0] - nx * h, p[1] - ny * h]); });
  const cap = (p, from) => {                     // полукруг вокруг конца черты
    const a0 = Math.atan2(from[1] - p[1], from[0] - p[0]);
    return Array.from({ length: 7 }, (_, k) => { const a = a0 - Math.PI * (k + 1) / 8; return [p[0] + h * Math.cos(a), p[1] + h * Math.sin(a)]; });
  };
  const ring = [...left, ...cap(pts[n - 1], left[n - 1]), ...right.reverse(), ...cap(pts[0], right[right.length - 1])];
  return `M ${ring.map(([x, y]) => `${r1(x)} ${r1(y)}`).join(' L ')} Z`;
}

/* Данные буквы для тренажёра письма: { strokes: [контур], medians: [[[x, y], …]] } */
const cache = {};
export function letterData(ch) {
  if (!ALL[ch]) return null;
  if (!cache[ch]) {
    const medians = ALL[ch].map(s => s.map(([x, y]) => [Math.round(x), Math.round(y)]));
    cache[ch] = { strokes: ALL[ch].map(s => outline(s)), medians };
  }
  return cache[ch];
}
