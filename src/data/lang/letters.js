/* ---------- примитивы: отрезок и дуга эллипса (углы в градусах, против часовой — положительные) ---------- */
function L(x1, y1, x2, y2) {
  const n = Math.max(2, Math.round(Math.hypot(x2 - x1, y2 - y1) / 40));
  return Array.from({ length: n + 1 }, (_, i) => [x1 + (x2 - x1) * i / n, y1 + (y2 - y1) * i / n]);
}
function E(cx, cy, rx, ry, a0, a1) {
  const n = Math.max(4, Math.round(Math.abs(a1 - a0) / 10));
  return Array.from({ length: n + 1 }, (_, i) => {
    const a = (a0 + (a1 - a0) * i / n) * Math.PI / 180;
    return [cx + rx * Math.cos(a), cy + ry * Math.sin(a)];
  });
}
/* Волна для тильды над ñ */
function wave(x1, x2, y, amp) {
  return Array.from({ length: 13 }, (_, i) => [x1 + (x2 - x1) * i / 12, y + amp * Math.sin(2 * Math.PI * i / 12)]);
}
/* Черта из нескольких кусков: точки стыков не повторяются */
const S = (...parts) => parts.reduce((out, p) => {
  const last = out[out.length - 1];
  return out.concat(last && Math.hypot(last[0] - p[0][0], last[1] - p[0][1]) < 1 ? p.slice(1) : p);
}, []);

