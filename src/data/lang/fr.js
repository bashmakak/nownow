/* Неразрывный пробел перед ? ! : ; и внутри «ёлочек» — так требует французская типографика.
   Русские строки этим не затрагиваются: в русском пробела перед знаками нет */
function fixSpaces(x) {
  if (typeof x === 'string') return x.replace(/ ([?!:;»])/g, ' $1').replace(/« /g, '« ');
  if (Array.isArray(x)) return x.map(fixSpaces);
  if (x && typeof x === 'object') return Object.fromEntries(Object.entries(x).map(([k, v]) => [k, fixSpaces(v)]));
  return x;
}

