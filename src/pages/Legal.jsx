  terms: { title: 'Пользовательское соглашение', edition: EDITION.terms, lead: 'Правила пользования сайтом NowNow: что можно, чего нельзя и за что отвечает каждая сторона.', sections: TERMS, other: ['/legal/privacy', 'Политика конфиденциальности'] },
