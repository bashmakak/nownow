function Doc({ kind }) {
  const d = DOC[kind];
  useTitle(d.title);
  const [params] = useSearchParams();
  const target = params.get('s');
  const go = id => document.getElementById(`s-${id}`)?.scrollIntoView({ behavior: 'smooth', block: 'start' });
  // ссылка вида /legal/privacy?s=cookies открывает документ на нужном разделе
  useEffect(() => { if (target) setTimeout(() => document.getElementById(`s-${target}`)?.scrollIntoView({ block: 'start' }), 60); }, [target, kind]);

  return (
    <section className="page">
      <div className="wrap legal">
        <header className="page-head">
          <span className="label">Редакция от {d.edition}</span>
          <h1 className="h1">{d.title}</h1>
          <p className="lead">{d.lead}</p>
        </header>
        {!LEGAL_READY && (
          <div className="note-box legal-draft" role="note">
            <Icon name="info" size={20} />
            <p><b>Черновик.</b> В документе пока не указаны сведения о владельце сайта: имя или название и адрес для обращений. До их появления текст не считается окончательным.</p>
          </div>
        )}
        <nav className="legal-toc" aria-label="Разделы документа">
          <ol>{d.sections.map(([id, title]) => <li key={id}><button type="button" onClick={() => go(id)}>{title}</button></li>)}</ol>
        </nav>
        <div className="legal-body">
          {d.sections.map(([id, title, body], i) => (
            <section key={id} id={`s-${id}`} aria-labelledby={`h-${id}`}>
              <h2 className="h3" id={`h-${id}`}><span className="num">{i + 1}.</span> {title}</h2>
              {body}
            </section>
          ))}
        </div>
        <p className="legal-foot">Смотрите также: <Link to={d.other[0]}>{d.other[1]}</Link></p>
      </div>
    </section>
  );
}

